"""
fai_generate_objective_questions.py

Downloads MMLU subsets from Hugging Face and samples objective questions
for each FAI benchmark dimension.

Character-Biblical objective questions are generated by GPT-4o separately
and are NOT handled by this script.

Directory structure:
    Run this script from your project root (where your data/ folder is).

Output:
    data/questions/character_secular_objective.csv   (30 questions)
    data/questions/relationships_objective.csv        (60 questions)
    data/questions/finance_objective.csv              (60 questions)
    data/questions/health_objective.csv               (60 questions)
    data/questions/happiness_objective.csv            (60 questions)
    data/questions/faith_objective.csv                (60 questions)
    data/questions/meaning_objective.csv              (60 questions)

Requirements:
    pip install datasets pandas
"""

import random
import pandas as pd
from pathlib import Path
from datasets import load_dataset

# ── Config ────────────────────────────────────────────────────────────────────

RANDOM_SEED = 42
random.seed(RANDOM_SEED)

OUTPUT_DIR = Path("data/questions")
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

# ── Dimension → MMLU subset mapping ──────────────────────────────────────────
# Each entry specifies which MMLU subsets to pool from and how many to sample.
# Character-Biblical is excluded — those are GPT-4o generated separately.

DIMENSION_CONFIG = {
    "character_secular": {
        "subsets": ["moral_scenarios"],
        "n": 30,   # Only 30 here; the other 30 come from biblical objective
    },
    "relationships": {
        "subsets": ["sociology", "human_sexuality"],
        "n": 60,
    },
    "finance": {
        "subsets": ["econometrics", "high_school_macroeconomics", "high_school_microeconomics"],
        "n": 60,
    },
    "health": {
        "subsets": ["anatomy", "clinical_knowledge", "medical_genetics"],
        "n": 60,
    },
    "happiness": {
        "subsets": ["high_school_psychology", "professional_psychology"],
        "n": 60,
    },
    "faith": {
        "subsets": ["world_religions"],
        "n": 60,
    },
    "meaning": {
        "subsets": ["human_aging", "professional_psychology"],
        "n": 60,   # 30 from each subset (50/50 split)
    },
}

# ── Helpers ───────────────────────────────────────────────────────────────────

def load_mmlu_subset(subset_name: str) -> list[dict]:
    """Download one MMLU subset and return as a list of standardized dicts."""
    print(f"    Downloading: {subset_name}...")
    ds = load_dataset("cais/mmlu", subset_name, trust_remote_code=True)

    questions = []
    for item in ds["test"]:
        questions.append({
            "source":       subset_name,
            "type":         "objective",
            "question":     item["question"],
            "choice_a":     item["choices"][0],
            "choice_b":     item["choices"][1],
            "choice_c":     item["choices"][2],
            "choice_d":     item["choices"][3],
            "answer":       item["answer"],
            "answer_label": ["A", "B", "C", "D"][item["answer"]],
            "context":      "",
        })

    print(f"    Loaded {len(questions)} questions from {subset_name}.")
    return questions


def sample_evenly(all_questions_by_subset: dict, n_total: int, dimension: str) -> list[dict]:
    """
    Sample n_total questions evenly across subsets.
    If only one subset, sample all from it.
    Falls back to proportional sampling if counts are uneven.
    """
    subsets = list(all_questions_by_subset.keys())
    n_per_subset = n_total // len(subsets)
    remainder = n_total % len(subsets)

    sampled = []
    for i, (subset, questions) in enumerate(all_questions_by_subset.items()):
        # Give remainder to first subset
        n = n_per_subset + (1 if i < remainder else 0)

        if len(questions) < n:
            print(f"    [WARN] {subset} only has {len(questions)} questions, needed {n}. Taking all.")
            n = len(questions)

        sampled.extend(random.sample(questions, n))

    print(f"    Sampled {len(sampled)}/{n_total} questions for {dimension}.")
    return sampled


def save_dimension(dimension: str, rows: list[dict]):
    """Save questions for one dimension to CSV."""
    df = pd.DataFrame(rows)
    df.insert(0, "dimension", dimension)
    df.insert(0, "id", [f"{dimension}_obj_{i+1:03d}" for i in range(len(df))])

    col_order = [
        "id", "dimension", "source", "type",
        "question", "choice_a", "choice_b", "choice_c", "choice_d",
        "answer", "answer_label", "context"
    ]
    df = df[col_order]

    output_path = OUTPUT_DIR / f"{dimension}_objective.csv"
    df.to_csv(output_path, index=False, encoding="utf-8")
    print(f"    Saved → {output_path}")
    return df


# ── Main ──────────────────────────────────────────────────────────────────────

def main():
    print("\nFAI Objective Question Sampler")
    print("=" * 60)
    print(f"Output directory: {OUTPUT_DIR}")
    print(f"Random seed: {RANDOM_SEED}\n")

    summary = []

    for dimension, config in DIMENSION_CONFIG.items():
        print(f"\n[{dimension}]")
        print(f"  Subsets : {config['subsets']}")
        print(f"  Target  : {config['n']} questions")

        # Load all subsets for this dimension
        questions_by_subset = {}
        for subset in config["subsets"]:
            questions_by_subset[subset] = load_mmlu_subset(subset)

        # Sample evenly across subsets
        sampled = sample_evenly(questions_by_subset, config["n"], dimension)

        # Save
        df = save_dimension(dimension, sampled)
        summary.append((dimension, len(df), config["n"]))

    # Summary
    print(f"\n{'=' * 60}")
    print("SUMMARY")
    print(f"{'=' * 60}")
    for dim, count, expected in summary:
        status = "✅" if count == expected else f"⚠ got {count}, expected {expected}"
        print(f"  {dim:<25} {count:>3} questions   [{status}]")

    print(f"\n{'=' * 60}")
    print("NOTE: character_biblical_objective.csv is NOT generated here.")
    print("      Run fai_generate_biblical_objective.py separately for those 30 questions.")
    print(f"{'=' * 60}\n")


if __name__ == "__main__":
    main()
